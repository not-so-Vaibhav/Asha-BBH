export type Language = 'en' | 'hi' | 'mr';
export type TextSize = 'normal' | 'large' | 'xlarge';
export type BeneficiaryKind = 'Pregnant' | 'Newborn' | 'Child';
export type Beneficiary = { id:string; name:string; kind:BeneficiaryKind; age:string; due:string; villageId:string };
export type VisitType = 'ANC' | 'PNC' | 'HBNC' | 'HBYC' | 'Immunisation' | 'General';
export type VisitFields = { beneficiaryId:string; visitType:VisitType; weight:string; vaccinationsDue:string; nextVisitDate:string };
export type Correction = { field:keyof VisitFields; oldValue:string; newValue:string; timestamp:string };
export type DangerSource = 'asr' | 'manual';
export type VisitRecord = {
  id:string;
  beneficiaryId:string;
  beneficiaryName:string;
  fields:VisitFields;
  timestamp:string;
  transcript:string;
  dangerSign:boolean;
  needsReview:boolean;
  referralId?:string;
  corrections:Correction[];
  idempotencyKey?:string;
  duplicateOverrideReason?:string;
};
export type Referral = { id:string; ruleId:string; category:string; timestamp:string; facility:string; status:'Pending review'; transcriptExcerpt:string; needsReview:boolean; visitId?:string; beneficiaryId:string; source?:DangerSource };
export type AuditEvent = {
  id:string;
  type:'danger_triggered'|'visit_saved'|'duplicate_override';
  timestamp:string;
  beneficiaryId:string;
  ruleId?:string;
  referralId?:string;
  source?:DangerSource;
  transcriptUsed?:string;
  visitType?:VisitType;
  existingVisitId?:string;
  reason?:string;
};
export type FollowUp = { id:string; beneficiaryId:string; beneficiaryName:string; date:string; status:'Upcoming'|'Pending'|'Overdue'|'Done'; visitId:string };
export type Rule = { id:string; category:string; appliesTo:BeneficiaryKind[]; patterns:Record<Language|'mix',string[]>; pending_review?:Record<'hi'|'mr',string[]>; source:string; version:string; wording:Record<Language,string> };
